import {run} from './harness.mjs';
run(`
  clean(); makeMap(); resetPlayers(6);
  players.forEach(p=>{p.pick='cannon';p.built=true;});
  players[0].built=false;round=1; beginBuild();
  aim={x:14.2,y:2.3,z:1.7}; updateGhost();
  const initialPosition=ghost.position.clone();
  const initialQuaternion=ghost.quaternion.clone();
  const canvas=renderer.domElement;
  canvas.emit('pointerenter',{clientX:150,clientY:100});
  canvas.emit('pointermove',{clientX:250,clientY:130,buttons:0});
  assert.equal(buildView.yaw,.5,'mouse movement without buttons changes build camera yaw');
  tick(last+16);
  assert(ghost.position.equals(initialPosition),'camera drag leaves object position fixed');
  assert(ghost.quaternion.equals(initialQuaternion),'camera drag leaves world orientation fixed');
  window.emit('keydown',{code:'KeyR',repeat:false,preventDefault(){}});
  window.emit('keyup',{code:'KeyR'});
  assert(Math.abs(ghost.rotation.y-Math.PI/2)<1e-9,'R rotates object by 90 degrees');
  assert.equal(buildView.yaw,.5,'R leaves camera yaw fixed');
  const rotatedQuaternion=ghost.quaternion.clone();
  canvas.emit('pointermove',{clientX:150,clientY:80,buttons:0});
  tick(last+16);
  assert(ghost.quaternion.equals(rotatedQuaternion),'further orbit preserves rotated object');
  $('autoPlace').onclick();
  assert(ghost.quaternion.equals(rotatedQuaternion),'AI position suggestion preserves orientation');
  beginRace();
  const placedObject=surfaces.at(-1);
  assert.equal(placedObject.angle,Math.PI/2,'timeout commits selected orientation');
  assert(placedObject.mesh.quaternion.equals(rotatedQuaternion),'committed orientation matches preview');
  const beforeYaw=yaw;
  canvas.emit('pointerenter',{clientX:150,clientY:100});
  canvas.emit('pointermove',{clientX:200,clientY:100,buttons:0});
  assert.equal(yaw,beforeYaw+.25,'race camera also follows mouse without buttons');
  console.log('PASS: no-button mouse look, camera/object independence, position suggestion, timed placement');
`);
